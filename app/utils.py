"""ابزارهای مشترک سامانه."""
from __future__ import annotations

# ارقام فارسی (۰-۹) و عربی (٠-٩) به معادل انگلیسی
_FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹"
_AR_DIGITS = "٠١٢٣٤٥٦٧٨٩"
_DIGIT_MAP = str.maketrans(_FA_DIGITS + _AR_DIGITS, "0123456789" * 2)


def normalize_digits(text: str) -> str:
    """تبدیل ارقام فارسی/عربی به انگلیسی.

    ربات کد اتصال را با ارقام انگلیسی می‌فرستد، اما کاربر فارسی‌زبان ممکن است
    همان کد را روی صفحه‌کلید فارسی (۴۸۳۹۲۰) تایپ کند. مقایسه متنی در پایگاه
    داده در این حالت شکست می‌خورد («کد اشتباه است یا منقضی شده است») در حالی
    که کد کاملاً درست بوده است. این تابع در لایه ورودی اعمال می‌شود.
    """
    if not text:
        return text
    return text.translate(_DIGIT_MAP)
